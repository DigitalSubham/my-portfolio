import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { createHmac, randomUUID, scryptSync } from "node:crypto";
import { mkdir, readFile } from "node:fs/promises";
import nextEnv from "@next/env";
import { neon } from "@neondatabase/serverless";

nextEnv.loadEnvConfig(process.cwd());
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || "playwright");
const sql = neon(process.env.DATABASE_URL), base = process.env.PRACTICE_TEST_URL || "http://localhost:3000";
const questions = JSON.parse(await readFile(new URL("../db/seeds/history-questions.json", import.meta.url), "utf8"));
const byId = new Map(questions.map((q) => [q.id, q]));
const email = `history-test-${randomUUID()}@example.invalid`, password = randomUUID(), salt = randomUUID();
const hash = scryptSync(password, salt, 64).toString("hex");
const [admin] = await sql`INSERT INTO admins (email, password_hash, password_salt) VALUES (${email}, ${hash}, ${salt}) RETURNING id`;
const unsigned = [{ alg: "HS256", typ: "JWT" }, { sub: String(admin.id), email, exp: Math.floor(Date.now() / 1000) + 3600 }].map((part) => Buffer.from(JSON.stringify(part)).toString("base64url")).join(".");
const token = `${unsigned}.${createHmac("sha256", process.env.JWT_SECRET).update(unsigned).digest("base64url")}`;
const cookie = { name: "portfolio_admin_token", value: token, url: base };
let browser;
try {
  browser = await chromium.launch({ headless: true, channel: "chrome" });
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await desktop.addCookies([cookie]);
  const dsa = { version: 1, view: "home", progress: { pyq: { r: { "PYQ-01": [1, 1, 1] }, h: "1" } }, session: null };
  assert.equal((await desktop.request.post(`${base}/api/practice/dsa/progress`, { headers: { Origin: base }, data: { revision: 0, snapshot: dsa } })).status(), 200);
  const bank = await (await desktop.request.get(`${base}/api/practice/history/questions`)).json();
  assert.deepEqual(bank.questions, questions);
  const page = await desktop.newPage(), errors = [], calls = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("request", (r) => { if (r.url().includes("/api/practice/")) calls.push({ url: r.url(), method: r.method() }); });
  await page.goto(`${base}/practice/history?chapter=chapter-01`);
  await page.getByRole("heading", { name: "Bihar History & Indian National Movement", exact: true }).waitFor();
  await page.locator('.setup[data-for="chapter-01"]').waitFor();
  assert.equal(await page.locator(".ledger > article").count(), 24);
  assert.equal(calls.length, 2);
  await page.locator('[data-act="start"][data-key="chapter-01"]').click();
  for (let i = 0; i < 5; i++) {
    const id = await page.locator(".qid").innerText();
    await page.locator(`[data-act="pick"][data-i="${"ABCDE".indexOf(byId.get(id).ans)}"]`).click();
    await page.locator('[data-act="next"]').click();
  }
  assert.equal(calls.length, 2, "history correct answers and navigation remain local");
  const savedId = await page.locator(".qid").innerText();
  await page.locator(`[data-act="pick"][data-i="${("ABCDE".indexOf(byId.get(savedId).ans) + 1) % 5}"]`).click();
  await page.getByRole("status").filter({ hasText: "Saved to your account" }).waitFor();
  const snapshot = await (await desktop.request.get(`${base}/api/practice/history/progress`)).json();
  assert.equal(snapshot.snapshot.session.i, 5);
  assert.equal(snapshot.snapshot.session.key, "chapter-01");
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true });
  await phone.addCookies([cookie]);
  const mobile = await phone.newPage();
  mobile.on("pageerror", (e) => errors.push(e.message));
  await mobile.goto(`${base}/practice/history`);
  await mobile.locator(".qid").waitFor();
  assert.equal(await mobile.locator(".qid").innerText(), savedId);
  await mobile.locator('[data-act="previous"]').click();
  assert.equal(await mobile.locator(".opt.picked").count(), 1);
  await mobile.locator('[data-act="next"]').click();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mkdir("screenshots/practice", { recursive: true });
  await mobile.screenshot({ path: "screenshots/practice/history-quiz-mobile.png", fullPage: true });
  await mobile.locator('[data-act="quit"]').click();
  await mobile.getByRole("status").filter({ hasText: "Saved to your account" }).waitFor();
  await mobile.locator('[data-act="reset"]').click();
  await mobile.getByRole("button", { name: "Yes, clear my progress" }).click();
  await mobile.getByRole("status").filter({ hasText: "Saved to your account" }).waitFor();
  assert.deepEqual((await (await desktop.request.get(`${base}/api/practice/dsa/progress`)).json()).snapshot, dsa, "history reset cannot erase DSA progress");

  const notes = await desktop.newPage();
  notes.on("pageerror", (e) => errors.push(e.message));
  await notes.goto(`${base}/practice/history/notes`);
  await notes.getByRole("heading", { name: "Chapters", exact: true }).waitFor();
  assert.equal(await notes.locator(".chapter-list > li").count(), 24);
  await notes.getByRole("searchbox", { name: "Search chapters" }).fill("Champaran");
  assert.equal(await notes.locator(".chapter-list > li").count(), 1);
  await notes.locator('.chapter-list nav a[href="/practice/history/notes/chapter-15"]').click();
  await notes.locator("#history-note h1").waitFor();
  assert.match(await notes.locator("#history-note h1").innerText(), /चंपारण/);
  assert.ok(await notes.locator(".gloss").count() > 0);
  assert.ok(await notes.locator(".table-scroll").count() > 0);
  await notes.getByRole("button", { name: "Increase text size" }).click();
  assert.equal(await notes.locator("#history-note").evaluate((el) => getComputedStyle(el).fontSize), "19px");
  await notes.locator("#history-note h1").scrollIntoViewIfNeeded();
  await notes.screenshot({ path: "screenshots/practice/history-notes-desktop.png" });
  await notes.reload();
  await notes.locator("#history-note h1").waitFor();
  await notes.waitForFunction(() => getComputedStyle(document.getElementById("history-note")).fontSize === "19px");
  assert.equal(await notes.locator("#history-note").evaluate((el) => getComputedStyle(el).fontSize), "19px");
  await notes.goto(`${base}/practice/history/notes`);
  await notes.getByRole("link", { name: "Continue reading" }).waitFor();
  const reader = await phone.newPage();
  reader.on("pageerror", (e) => errors.push(e.message));
  await reader.goto(`${base}/practice/history/notes/chapter-15`);
  await reader.locator("#history-note h1").waitFor();
  await reader.locator("#history-note h1").scrollIntoViewIfNeeded();
  assert.equal(await reader.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await reader.screenshot({ path: "screenshots/practice/history-notes-mobile.png" });
  await reader.locator(".table-scroll").first().scrollIntoViewIfNeeded();
  assert.equal(await reader.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await reader.screenshot({ path: "screenshots/practice/history-table-mobile.png" });
  for (const chapter of ["chapter-01", "chapter-24", "sources"]) {
    const response = await desktop.request.get(`${base}/practice/history/notes/${chapter}`);
    assert.equal(response.status(), 200, chapter);
    assert.match(await response.text(), /history-note/);
  }
  const pdf = await desktop.request.get(`${base}/study/history/complete-notes-hindi.pdf`);
  assert.equal(pdf.status(), 200); assert.match(pdf.headers()["content-type"], /application\/pdf/);
  assert.equal((await desktop.request.get(`${base}/api/practice/missing/questions`)).status(), 404);
  const badHistory = await desktop.request.post(`${base}/api/practice/history/progress`, { headers: { Origin: base }, data: { revision: 0, snapshot: dsa } });
  assert.equal(badHistory.status(), 400);
  assert.deepEqual(errors, []);
  console.log("Passed: all 880 DB questions, 24 chapters, local correct-answer navigation, wrong-answer save, cross-device resume, subject-isolated reset, Hindi notes, chapter search, persisted font size, mobile tables, source notes and PDF download.");
} finally {
  if (browser) await browser.close();
  await sql`DELETE FROM admins WHERE id = ${admin.id} AND email = ${email}`;
}
