import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHmac, randomUUID, scryptSync } from 'node:crypto';
import { mkdir, readFile } from 'node:fs/promises';
import nextEnv from '@next/env';
import { neon } from '@neondatabase/serverless';

nextEnv.loadEnvConfig(process.cwd());
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PRACTICE_TEST_URL || 'http://localhost:3000';
const questions = JSON.parse(await readFile(new URL('../db/seeds/oops-questions.json', import.meta.url), 'utf8'));
const chapters = JSON.parse(await readFile(new URL('../src/content/oops/chapters.json', import.meta.url), 'utf8'));
const sql = neon(process.env.DATABASE_URL);
const email = `oops-test-${randomUUID()}@example.invalid`, salt = randomUUID();
const hash = scryptSync(randomUUID(), salt, 64).toString('hex');
const [admin] = await sql`INSERT INTO admins (email, password_hash, password_salt) VALUES (${email}, ${hash}, ${salt}) RETURNING id`;
const unsigned = [{ alg: 'HS256', typ: 'JWT' }, { sub: String(admin.id), email, exp: Math.floor(Date.now() / 1000) + 3600 }].map((value) => Buffer.from(JSON.stringify(value)).toString('base64url')).join('.');
const token = `${unsigned}.${createHmac('sha256', process.env.JWT_SECRET).update(unsigned).digest('base64url')}`;
const cookie = { name: 'portfolio_admin_token', value: token, url: base };
const localKey = `practice-oops-session-v1-${admin.id}`;
const [review] = questions.filter((q) => q.unscored);
const [right, wrong] = questions.filter((q) => !q.unscored);
const snapshot = { version: 1, progress: {}, view: 'q', session: { kind: 'practice', title: 'OOP verification', list: [review.id, right.id, wrong.id], i: 0, picks: {}, key: null, done: false } };
let browser;
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const desktop = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  await desktop.addCookies([cookie]);
  const page = await desktop.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('dialog', (dialog) => dialog.accept());
  page.setDefaultTimeout(30000);
  await page.goto(`${base}/practice/oops/notes`);
  await page.evaluate(({ key, snapshot }) => localStorage.setItem(key, JSON.stringify({ revision: 0, snapshot })), { key: localKey, snapshot });
  const posts = [];
  page.on('request', (request) => { if (request.url().includes('/api/practice/oops/progress') && request.method() === 'POST') posts.push(request.postDataJSON()); });
  await page.goto(`${base}/practice/oops`);
  await page.locator('.qid').waitFor();
  assert.equal(await page.locator('.qid').innerText(), review.id);
  await page.locator('[data-act="pick"][data-i="0"]').click();
  assert.match(await page.locator('.verdict').innerText(), /not scored/);
  assert.equal(await page.locator('.opt.right,.opt.wrong').count(), 0);
  await page.waitForTimeout(1100);
  assert.equal(posts.length, 0, 'review choices do not trigger wrong-answer saving');
  const local = await page.evaluate((key) => JSON.parse(localStorage.getItem(key)), localKey);
  assert.deepEqual(local.snapshot.progress, {});
  await page.locator('[data-act="next"]').click();
  await page.locator(`[data-act="pick"][data-i="${'ABCDE'.indexOf(right.ans)}"]`).click();
  await page.locator('[data-act="next"]').click();
  assert.equal(posts.length, 0, 'correct answers and navigation stay local');
  await page.locator(`[data-act="pick"][data-i="${('ABCDE'.indexOf(wrong.ans) + 1) % 5}"]`).click();
  await page.getByRole('status').filter({ hasText: 'Saved to your account' }).waitFor();
  assert.equal(posts.length, 1);
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobileContext.addCookies([cookie]);
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', (error) => errors.push(error.message));
  await mobile.goto(`${base}/practice/oops`);
  await mobile.locator('.qid').waitFor();
  assert.equal(await mobile.locator('.qid').innerText(), wrong.id, 'another device resumes the saved question');
  await mobile.locator('[data-act="next"]').click();
  assert.match(await mobile.locator('.result-head h1').innerText(), /1 \/ 2 correct/);
  assert.equal(await mobile.getByText('REVIEW ONLY', { exact: true }).count(), 1);
  assert.equal((await mobileContext.request.get(`${base}/api/practice/history/progress`).then((r) => r.json())).snapshot, null);
  await page.close();
  await mobile.locator('[data-act="quit"]').last().click();
  await mobile.locator('[data-act="setup"][data-key="test"]').click();
  await mobile.locator('[data-act="start-test"]').click();
  const timed = await mobile.evaluate((key) => JSON.parse(localStorage.getItem(key)).snapshot.session, localKey);
  assert.equal(timed.list.length, 16);
  assert.ok(timed.list.every((id) => !questions.find((q) => q.id === id).unscored));
  await mobile.goto(`${base}/practice/oops/notes`);
  assert.equal(await mobile.locator('#oops-note > .oop-topic').count(), 20);
  await mkdir('screenshots/practice', { recursive: true });
  await mobile.goto(`${base}/practice/oops/notes/refresh`);
  await mobile.locator('#oops-note pre').first().scrollIntoViewIfNeeded();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: 'screenshots/practice/oops-notes-mobile.png' });
  await mobile.getByRole('button', { name: 'Increase text size' }).click();
  assert.equal(await mobile.locator('.reading-tools output').innerText(), '19');
  assert.equal(await mobile.evaluate(() => localStorage.getItem('history-font-size')), null);
  assert.equal(new URL(mobile.url()).hash, '#refresh');
  assert.equal(await mobile.locator('#oops-note img').count(), 0);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const reader = await desktop.newPage();
  for (const chapter of chapters) {
    const response = await reader.goto(`${base}/practice/oops/notes/${chapter.key}`);
    assert.equal(response.status(), 200);
    assert.equal(await reader.locator(`#${chapter.key} > h2`).innerText(), chapter.title);
    assert.equal(new URL(reader.url()).hash, `#${chapter.key}`);
    assert.equal(await reader.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await reader.goto(`${base}/practice/oops/notes/inheritance`);
  await reader.screenshot({ path: 'screenshots/practice/oops-notes-desktop.png' });
  assert.equal((await reader.goto(`${base}/practice/oops/notes/sources`)).status(), 200);
  for (const doc of ['notes', 'assignment-1', 'assignment-2']) assert.equal((await desktop.request.get(`${base}/study/oops/${doc}.pdf`)).status(), 200);
  assert.deepEqual(errors, []);
  console.log('Passed: continuous database notes, mobile reader, PDF downloads, review-only scoring, no per-question saves, wrong-answer save, cross-device resume, isolated subjects and timed-test exclusions.');
} finally {
  if (browser) await browser.close();
  await sql`DELETE FROM admins WHERE id = ${admin.id} AND email = ${email}`;
}
